import { z } from "zod";

export const leadFormSchema = z.object({
  firstName: z.string().trim().min(1, "First name is required"),
  lastName: z.string().trim().min(1, "Last name is required"),
  company: z.string().trim().min(1, "Company is required"),
  designation: z.string().trim().optional(),
  email: z.string().trim().email("Enter a valid email address"),
  phone: z.string().trim().min(7, "Enter a valid phone number"),
  whatsapp: z.string().trim().optional(),
  website: z.string().trim().optional().refine((value) => !value || /^(https?:\/\/)/i.test(value), "Enter a valid website URL"),
  industry: z.string().trim().optional(),
  companySize: z.string().trim().optional(),
  country: z.string().trim().optional(),
  state: z.string().trim().optional(),
  city: z.string().trim().optional(),
  zipCode: z.string().trim().optional().refine((value) => !value || /^([A-Z]{1,2}\d[A-Z\d]?\s?\d[A-Z]{2}|\d{4,6})$/i.test(value), "Enter a valid ZIP code"),
  leadSource: z.string().trim().optional(),
  status: z.enum(["New", "Qualified", "Follow-up", "Won", "Lost"]),
  priority: z.enum(["Low", "Medium", "High", "Urgent"]),
  interestLevel: z.enum(["Low", "Medium", "High", "Very High"]),
  assignedTo: z.string().trim().optional(),
  dealValue: z.string().trim().optional().refine((value) => !value || /^\d+(\.\d{1,2})?$/.test(value), "Enter a valid deal value"),
  product: z.string().trim().optional(),
  quantity: z.string().trim().optional().refine((value) => !value || /^\d+$/.test(value), "Quantity must be a whole number"),
  budget: z.string().trim().optional().refine((value) => !value || /^\d+(\.\d{1,2})?$/.test(value), "Enter a valid budget"),
  expectedPurchaseDate: z.string().trim().optional(),
  nextFollowUpDate: z.string().trim().optional(),
  reminderTime: z.string().trim().optional(),
  preferredContactMethod: z.enum(["Email", "Phone", "WhatsApp", "Meeting"]),
  notes: z.string().trim().max(1200, "Notes must be under 1200 characters").optional(),
  attachments: z.array(z.object({ id: z.string(), name: z.string(), size: z.number(), type: z.string() })).optional(),
  tags: z.array(z.string()).optional(),
});

